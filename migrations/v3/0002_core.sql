-- v3/0002_core.sql (T112; docs/v3/DATA_MODEL.md sections 1, 2, 3.1, 3.2). Forward-only, never edit after release.
-- Run by `nzbd db migrate` as nzbd_owner (the one-shot setup service; `serve` never migrates, review M4), with
-- search_path = nzbd. The 2.x SQLite model (migrations/0001-0014) is the semantic reference: every CHECK and trigger
-- has an equivalent here.

-- Advisory lock keys (two-integer form, ARCHITECTURE v3 section 6). Namespace 0x6E7A6264 ('nzbd'); key 1 = account
-- domain, 2 = indexer, 3 = migrate, 4 = partition upkeep. Mirrored by `nzb_store::pg::lock` (a test pins them).
CREATE FUNCTION nzbd.lock_namespace() RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE
  SET search_path = nzbd, pg_temp AS $$ SELECT 1853514340 $$;
CREATE FUNCTION nzbd.account_domain_key() RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE
  SET search_path = nzbd, pg_temp AS $$ SELECT 1 $$;

-- The database clock in Unix seconds. Retention cutoffs, partition upkeep and purges use THIS clock, never a value
-- supplied by the caller (review M3, L4 b). Tests replace the function body (as the owner/superuser of their private
-- database) to freeze time; production code never takes a clock argument.
CREATE FUNCTION nzbd.db_clock() RETURNS bigint LANGUAGE sql STABLE
  SET search_path = nzbd, pg_temp AS $$ SELECT floor(extract(epoch FROM now()))::bigint $$;

-- Taxonomy. Rows are written by the owner step of `nzbd db migrate` from nzb-core's embedded taxonomy (the single
-- source of truth); nzbd_app may only read them.
CREATE TABLE category (
  id        integer PRIMARY KEY CHECK (id BETWEEN 1 AND 99999),
  parent_id integer REFERENCES category(id),
  name      text NOT NULL CHECK (octet_length(name) BETWEEN 1 AND 64)
);

-- 2.x `user` (a reserved word in Postgres). Rows are tombstoned, never deleted or replaced.
CREATE TABLE account (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username                text   NOT NULL,
  password_hash           text   NOT NULL CHECK (octet_length(password_hash) BETWEEN 1 AND 256),
  role                    text   NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin','member','viewer')),
  totp_secret_enc         bytea  CHECK (octet_length(totp_secret_enc) <= 256),
  totp_enabled            boolean NOT NULL DEFAULT false,
  totp_last_step          bigint,
  failed_logins           bigint NOT NULL DEFAULT 0,
  locked_until            bigint,
  last_failed_at          bigint,
  enroll_token_hash       bytea  CHECK (enroll_token_hash IS NULL OR octet_length(enroll_token_hash) = 32),
  enroll_token_expires    bigint,
  created_at              bigint NOT NULL,
  password_changed_at     bigint NOT NULL,
  disabled_at             bigint,
  deleted_at              bigint,
  created_by              bigint REFERENCES account(id),
  last_login_at           bigint,
  -- The 2.x admin rule (`display_name_is_valid`): 1..=32 of [A-Za-z0-9 ._-], no leading/trailing space.
  display_name            text   CHECK (display_name ~ '^[A-Za-z0-9._-]([A-Za-z0-9 ._-]{0,30}[A-Za-z0-9._-])?$'),
  credentials_replaced_at bigint,
  credentials_replaced_by bigint,
  -- 0014 (D32): normalised email, never unique (no oracle), never used to contact anyone.
  email                   text   CHECK (email IS NULL OR (octet_length(email) BETWEEN 6 AND 254
                                        AND email = lower(email) AND position('@' in email) > 1
                                        AND email ~ '^[a-z0-9.@_%+-]+$')),
  CONSTRAINT account_username_shape CHECK (username ~ '^[A-Za-z0-9._-]{1,64}$'
                                           OR (deleted_at IS NOT NULL AND username ~ '^~deleted~[0-9]+$'))
);
-- NOCASE uniqueness under the C ctype: lower() folds ASCII only, exactly SQLite's NOCASE (DATA_MODEL v3 section 1).
CREATE UNIQUE INDEX account_username     ON account (lower(username));
CREATE UNIQUE INDEX account_display_name ON account (lower(display_name)) WHERE deleted_at IS NULL;
CREATE INDEX account_active_admin ON account (id) WHERE role = 'admin' AND disabled_at IS NULL AND deleted_at IS NULL;

-- N5: ^user-[0-9]+$ is reserved for display handles (backstop for the CLI/invite checks).
CREATE FUNCTION nzbd.account_reserved_handle() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  IF lower(NEW.username) ~ '^user-[0-9]+$' THEN
    RAISE EXCEPTION 'RESERVED_LOGIN_NAME';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER account_reserved_handle BEFORE INSERT ON account
  FOR EACH ROW EXECUTE FUNCTION nzbd.account_reserved_handle();

-- 2.x user_no_replace: an insert that would collide with an existing id or (NOCASE) login name is refused, so no
-- ON CONFLICT clause can ever replace or silently skip an account row.
CREATE FUNCTION nzbd.account_no_replace() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM nzbd.account WHERE id = NEW.id OR lower(username) = lower(NEW.username)) THEN
    RAISE EXCEPTION 'ACCOUNT_ROWS_ARE_NEVER_REPLACED';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER account_no_replace BEFORE INSERT ON account
  FOR EACH ROW EXECUTE FUNCTION nzbd.account_no_replace();

-- SEC-062: never zero active admins, enforced by the database too. The trigger takes the account-domain advisory lock
-- itself before looking, so two demotions in two sessions (even raw SQL that skipped the application lock) are
-- serialized and the second one sees the first under READ COMMITTED (the check statement takes a fresh snapshot after
-- the lock is granted): no write skew.
CREATE FUNCTION nzbd.account_keep_one_admin() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(nzbd.lock_namespace(), nzbd.account_domain_key());
  IF NOT EXISTS (SELECT 1 FROM nzbd.account
                 WHERE id <> OLD.id AND role = 'admin' AND disabled_at IS NULL AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'LAST_ADMIN';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER account_keep_one_admin BEFORE UPDATE OF role, disabled_at, deleted_at ON account
  FOR EACH ROW
  WHEN (OLD.role = 'admin' AND OLD.disabled_at IS NULL AND OLD.deleted_at IS NULL
        AND (NEW.role <> 'admin' OR NEW.disabled_at IS NOT NULL OR NEW.deleted_at IS NOT NULL))
  EXECUTE FUNCTION nzbd.account_keep_one_admin();

-- Accounts are tombstoned, never deleted (ids stay unique forever). nzbd_app has no DELETE grant either.
CREATE FUNCTION nzbd.account_no_row_delete() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  RAISE EXCEPTION 'ACCOUNT_ROWS_ARE_TOMBSTONED';
END $$;
CREATE TRIGGER account_no_row_delete BEFORE DELETE ON account
  FOR EACH ROW EXECUTE FUNCTION nzbd.account_no_row_delete();

-- Library. Not partitioned (global UNIQUE (sha256), PK lookups only; DATA_MODEL v3 section 2).
CREATE TABLE release (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256                bytea  NOT NULL UNIQUE CHECK (octet_length(sha256) = 32),
  title                 text   NOT NULL CHECK (octet_length(title) BETWEEN 1 AND 512),
  category_id           integer NOT NULL REFERENCES category(id),
  category_source       text   NOT NULL DEFAULT 'fallback'
                          CHECK (category_source IN ('scene','upload','meta','fallback','manual')),
  category_overridden   boolean NOT NULL DEFAULT false,
  posted_at             bigint,
  ingested_at           bigint NOT NULL,
  total_bytes           bigint NOT NULL CHECK (total_bytes >= 0),
  poster                text   CHECK (octet_length(poster) <= 1024),
  file_count            integer NOT NULL CHECK (file_count >= 0),
  segment_count         bigint NOT NULL CHECK (segment_count >= 0),
  missing_segment_count bigint NOT NULL DEFAULT 0 CHECK (missing_segment_count >= 0),
  par2_blocks           bigint NOT NULL DEFAULT 0 CHECK (par2_blocks >= 0),
  flags                 integer NOT NULL DEFAULT 0 CHECK (flags >= 0),
  nzb_size_bytes        bigint NOT NULL CHECK (nzb_size_bytes >= 0),
  source_name           text   CHECK (octet_length(source_name) <= 1024),
  source_label          text   CHECK (source_label IS NULL OR octet_length(source_label) BETWEEN 1 AND 64),
  origin                text   CHECK (origin IN ('watch','upload','api')),
  meta_json             text   CHECK (meta_json IS JSON OBJECT),
  scene_family          text   CHECK (scene_family IN ('tv','anime','movie','music')),
  scene_year            smallint CHECK (scene_year BETWEEN 1900 AND 2100),
  scene_season          integer CHECK (scene_season >= 0),
  scene_episode         integer CHECK (scene_episode >= 0),
  scene_resolution      text   CHECK (octet_length(scene_resolution) <= 512),
  scene_source          text   CHECK (octet_length(scene_source) <= 512),
  scene_codec           text   CHECK (octet_length(scene_codec) <= 512),
  scene_group           text   CHECK (octet_length(scene_group) <= 512),
  scene_title           text   CHECK (octet_length(scene_title) <= 512),
  scene_languages       text   CHECK (scene_languages IS JSON ARRAY),
  scene_json            text   CHECK (scene_json IS JSON OBJECT),
  added_by              bigint REFERENCES account(id),
  index_version         bigint NOT NULL DEFAULT 1 CHECK (index_version >= 1)
) WITH (fillfactor = 95, autovacuum_vacuum_scale_factor = 0.01, autovacuum_vacuum_insert_scale_factor = 0.01);
CREATE INDEX release_added_by ON release (added_by, id) WHERE added_by IS NOT NULL;
CREATE INDEX release_ingested_brin ON release USING brin (ingested_at) WITH (pages_per_range = 64);

-- Files: RANGE (release_id), 10,000,000 ids per partition, created by nzbd.ensure_file_partitions() (0008). No DEFAULT
-- partition (it would make later partition creation scan it).
CREATE TABLE nzb_file (
  release_id        bigint  NOT NULL REFERENCES release(id) ON DELETE CASCADE,
  idx               integer NOT NULL CHECK (idx >= 0),
  subject           text    NOT NULL CHECK (octet_length(subject) <= 4096),
  filename          text    CHECK (octet_length(filename) <= 255),
  kind              text    NOT NULL CHECK (kind IN ('video','audio','archive','par2','nfo','sfv','subtitle',
                                                     'image','nzb','executable','other')),
  poster            text    CHECK (octet_length(poster) <= 1024),
  posted_at         bigint,
  bytes             bigint  NOT NULL CHECK (bytes >= 0),
  segment_count     integer NOT NULL CHECK (segment_count >= 0),
  declared_segments integer CHECK (declared_segments >= 0),
  missing_ranges    text    CHECK (missing_ranges IS JSON),
  groups            text    CHECK (groups IS JSON ARRAY),
  PRIMARY KEY (release_id, idx)
) PARTITION BY RANGE (release_id);

-- Deleted releases (2.x 0008 + 0011 attribution): rows are MOVED here in one transaction.
CREATE TABLE release_trash (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_id    bigint NOT NULL,
  sha256         bytea  NOT NULL UNIQUE CHECK (octet_length(sha256) = 32),
  title          text   NOT NULL,
  category_id    integer NOT NULL,
  total_bytes    bigint NOT NULL CHECK (total_bytes >= 0),
  nzb_size_bytes bigint NOT NULL CHECK (nzb_size_bytes >= 0),
  file_count     integer NOT NULL CHECK (file_count >= 0),
  source_name    text,
  ingested_at    bigint NOT NULL,
  deleted_at     bigint NOT NULL,
  added_by       bigint,
  deleted_by     bigint
);
CREATE INDEX release_trash_deleted ON release_trash (deleted_at DESC, id DESC);

-- Exact per-category totals (stat tiles, degraded mode), maintained in the transaction of every change.
CREATE TABLE category_stats (
  category_id integer PRIMARY KEY REFERENCES category(id),
  releases bigint NOT NULL DEFAULT 0 CHECK (releases >= 0),
  files    bigint NOT NULL DEFAULT 0 CHECK (files >= 0),
  segments bigint NOT NULL DEFAULT 0 CHECK (segments >= 0),
  bytes    bigint NOT NULL DEFAULT 0 CHECK (bytes >= 0)
);

GRANT SELECT ON category TO nzbd_app;
GRANT SELECT, INSERT, UPDATE ON account TO nzbd_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON release, release_trash TO nzbd_app;
-- File rows are written once and leave with their release (ON DELETE CASCADE runs as the owner).
GRANT SELECT, INSERT ON nzb_file TO nzbd_app;
GRANT SELECT, UPDATE ON category_stats TO nzbd_app;
GRANT EXECUTE ON FUNCTION nzbd.lock_namespace(), nzbd.account_domain_key(), nzbd.db_clock() TO nzbd_app;
