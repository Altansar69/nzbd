-- Saved searches: private per account, stored as the validated, structured filter set of the index (a JSON object of
-- index parameter names to canonical values, re-validated by the index parser on every use; never Tantivy syntax and
-- never a URL). At most 25 per account and unique names per account are enforced by the store in one transaction under
-- the account-domain lock; the UNIQUE constraint is the backstop. Rows go with the account (deleted by the tombstone).
-- A 3.1 binary refuses a database with this migration (SCHEMA_NEWER); rollback = restore the pre-upgrade snapshot.
CREATE TABLE saved_search (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id   bigint NOT NULL REFERENCES account(id),
  name         text   NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  filters      text   NOT NULL CHECK (octet_length(filters) <= 2048 AND filters IS JSON OBJECT),
  created_at   bigint NOT NULL,
  last_seen_at bigint NOT NULL,
  CONSTRAINT saved_search_name_per_account UNIQUE (account_id, name)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON saved_search TO nzbd_app;
