-- v3/0003_auth.sql (T112; docs/v3/DATA_MODEL.md section 3.2; 2.x 0002, 0005, 0011, 0012, 0014). Forward-only.
-- Sessions and throttle tables are LOGGED on purpose (SEC-066: the persisted aggregate must survive a crash).
-- Counters of these small tables are bigint (not the smallint/integer of the first draft): the Rust side reads every
-- counter as i64 like 2.x, and sqlx decodes strictly by type; the space difference is irrelevant at tens of accounts.

CREATE TABLE recovery_code (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES account(id),
  code_hash  bytea  NOT NULL CHECK (octet_length(code_hash) = 32),
  used_at    bigint
);
CREATE INDEX recovery_code_account ON recovery_code (account_id);

CREATE TABLE session (
  id_hash       bytea  PRIMARY KEY CHECK (octet_length(id_hash) = 32),
  account_id    bigint NOT NULL REFERENCES account(id),
  stage         text   NOT NULL CHECK (stage IN ('pending_mfa','active')),
  csrf_token    bytea  NOT NULL CHECK (octet_length(csrf_token) BETWEEN 16 AND 64),
  created_at    bigint NOT NULL,
  last_seen_at  bigint NOT NULL,
  expires_at    bigint NOT NULL,
  ip            text   CHECK (octet_length(ip) <= 64),
  user_agent    text   CHECK (octet_length(user_agent) <= 512),
  enroll_proven boolean NOT NULL DEFAULT false,
  mfa_failures  bigint NOT NULL DEFAULT 0 CHECK (mfa_failures BETWEEN 0 AND 5),
  -- Insertion order: the tie-break of the per-user cap (2.x used the SQLite rowid).
  seq           bigint GENERATED ALWAYS AS IDENTITY UNIQUE
);
CREATE INDEX session_account ON session (account_id, stage);
CREATE INDEX session_expiry  ON session (expires_at);

-- One-time tokens: invitations and admin-issued recovery codes (2.x 0011 + 0014). Only a hash is stored.
CREATE TABLE invite (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purpose       text   NOT NULL CHECK (purpose IN ('invite','recover')),
  token_hash    bytea  NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
  username      text   CHECK (username ~ '^[A-Za-z0-9._-]{1,64}$'),
  role          text   CHECK (role IN ('member','viewer')),            -- NEVER 'admin' (D27)
  account_id    bigint REFERENCES account(id),
  created_by    bigint REFERENCES account(id),
  created_via   text   NOT NULL CHECK (created_via IN ('ui','cli')),
  created_at    bigint NOT NULL,
  expires_at    bigint NOT NULL,
  used_at       bigint,
  used_by       bigint REFERENCES account(id),
  revoked_at    bigint,
  name_refusals bigint NOT NULL DEFAULT 0 CHECK (name_refusals BETWEEN 0 AND 3),   -- D32
  CHECK (expires_at > created_at),
  CHECK (expires_at - created_at <= CASE purpose WHEN 'recover' THEN 86400 ELSE 604800 END),
  CHECK ((purpose = 'invite'  AND username IS NOT NULL AND role IS NOT NULL AND account_id IS NULL)
      OR (purpose = 'recover' AND account_id IS NOT NULL AND username IS NULL AND role IS NULL))
);
CREATE UNIQUE INDEX invite_open_username ON invite (lower(username))
  WHERE purpose = 'invite' AND used_at IS NULL AND revoked_at IS NULL;
CREATE UNIQUE INDEX invite_open_account  ON invite (account_id)
  WHERE purpose = 'recover' AND used_at IS NULL AND revoked_at IS NULL;
CREATE INDEX invite_expiry ON invite (expires_at);

-- Staged recovery (2.x 0011 M3): new credentials wait here until the enrollment confirmation commits them.
CREATE TABLE credential_staging (
  account_id      bigint PRIMARY KEY REFERENCES account(id),
  session_hash    bytea  NOT NULL UNIQUE CHECK (octet_length(session_hash) = 32),
  invite_id       bigint NOT NULL REFERENCES invite(id),
  issued_by       bigint,
  password_hash   text   NOT NULL CHECK (octet_length(password_hash) BETWEEN 1 AND 256),
  totp_secret_enc bytea  CHECK (octet_length(totp_secret_enc) <= 256),
  created_at      bigint NOT NULL,
  expires_at      bigint NOT NULL CHECK (expires_at > created_at AND expires_at - created_at <= 3600)
);

-- N4 backstops (the application also deletes explicitly; the commit never relies on these).
CREATE FUNCTION nzbd.staging_dies_with_session() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  DELETE FROM nzbd.credential_staging WHERE session_hash = OLD.id_hash;
  RETURN NULL;
END $$;
CREATE TRIGGER staging_dies_with_session AFTER DELETE ON session
  FOR EACH ROW EXECUTE FUNCTION nzbd.staging_dies_with_session();

CREATE FUNCTION nzbd.staging_dies_with_credential_change() RETURNS trigger LANGUAGE plpgsql
  SET search_path = nzbd, pg_temp AS $$
BEGIN
  DELETE FROM nzbd.credential_staging WHERE account_id = OLD.id;
  RETURN NULL;
END $$;
CREATE TRIGGER staging_dies_with_credential_change
  AFTER UPDATE OF password_hash, role, disabled_at, deleted_at ON account
  FOR EACH ROW EXECUTE FUNCTION nzbd.staging_dies_with_credential_change();

-- Persisted per-account aggregate throttle (N1/N2).
CREATE TABLE account_throttle (
  account_id        bigint  PRIMARY KEY REFERENCES account(id),
  hour_start        bigint  NOT NULL,
  hour_failures     bigint  NOT NULL CHECK (hour_failures >= 0),
  throttled_until   bigint,
  day_start         bigint  NOT NULL,
  day_mfa_failures  bigint  NOT NULL CHECK (day_mfa_failures >= 0),
  mfa_refused_until bigint
);

-- Hard lock keyed on (account, client IP /64) (M1).
CREATE TABLE login_lock (
  account_id   bigint  NOT NULL REFERENCES account(id),
  ip_key       text    NOT NULL CHECK (octet_length(ip_key) <= 64),
  failures     bigint  NOT NULL CHECK (failures >= 0),
  locked_until bigint,
  last_failure bigint  NOT NULL,
  PRIMARY KEY (account_id, ip_key)
);

-- The 5 most recent addresses of completed logins (N8).
CREATE TABLE user_known_ip (
  account_id bigint NOT NULL REFERENCES account(id),
  ip_key     text   NOT NULL CHECK (octet_length(ip_key) <= 64),
  last_seen  bigint NOT NULL,
  PRIMARY KEY (account_id, ip_key)
);

-- Upload-scoped API keys (2.x 0002, 0011, 0012).
CREATE TABLE api_key (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text   NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64),
  prefix       text   NOT NULL CHECK (octet_length(prefix) <= 16),
  key_hash     bytea  NOT NULL UNIQUE CHECK (octet_length(key_hash) = 32),
  scope        text   NOT NULL DEFAULT 'upload' CHECK (scope IN ('upload')),
  created_at   bigint NOT NULL,
  last_used_at bigint,
  revoked_at   bigint,
  owner_id     bigint REFERENCES account(id),
  rate_per_min bigint CHECK (rate_per_min BETWEEN 1 AND 30),
  revoked_by   bigint
);
CREATE INDEX api_key_owner ON api_key (owner_id) WHERE revoked_at IS NULL;

-- Per-user preferences (T120 schema; the feature itself lands with T120).
CREATE TABLE user_pref (
  account_id bigint  PRIMARY KEY REFERENCES account(id),
  hide_xxx   boolean NOT NULL DEFAULT false,
  theme      text    NOT NULL DEFAULT 'auto' CHECK (theme IN ('auto','light','dark')),
  updated_at bigint  NOT NULL
);

GRANT SELECT, INSERT, UPDATE, DELETE ON recovery_code, session, invite, credential_staging, account_throttle,
  login_lock, user_known_ip, api_key, user_pref TO nzbd_app;
